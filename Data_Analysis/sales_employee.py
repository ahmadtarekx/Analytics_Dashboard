# 4. EXECUTION WRAPPER
# ==========================================

def run_all_sales_employee_metrics(user_id):
    """Executes all metrics for a single Sales Representative."""
    results        = {}
    employee_funcs = [
        get_my_personal_info,
        get_my_total_sales_revenue,
        get_my_monthly_revenue,
        get_my_total_units_sold,
        get_my_average_deal_size,
        get_my_top_products,
        get_my_sales_trend,
        get_my_recent_transactions,
    ]
    for func in employee_funcs:
        try:
            results[func.__name__] = func(user_id)
        except Exception as e:
            results[func.__name__] = {"data": [], "warnings": [f"Error: {str(e)}"], "chart": None}
    return results

