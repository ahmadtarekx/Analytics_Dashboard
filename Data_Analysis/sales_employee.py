def get_my_personal_info(uid):
    """Employee's personal profile and assigned branch."""
    verify_employee(uid)
    query = f"""
        SELECT emp_id, First_Name, Last_Name, role, salary, phone, birth,
               departement_id, branch_id
        FROM employee WHERE emp_id = {uid}
    """
    df = pd.read_sql(query, engine)
    return {"data": safe_to_dict(df), "warnings": [], "chart": None}

def get_my_total_sales_revenue(uid):
    """Total all-time revenue generated by this employee."""
    verify_employee(uid)
    query = f"SELECT SUM(price) as my_total_revenue FROM employee_sales_log WHERE employee_id = {uid}"
    df    = pd.read_sql(query, engine)
    data  = safe_to_dict(df.round(2))
    warnings = evaluate_warnings(
        data, 'my_total_revenue', 1000, 'less',
        "You are currently below your sales target!"
    )
    return {"data": data, "warnings": warnings, "chart": None}

def get_my_monthly_revenue(uid):
    """Revenue for the current month only."""
    verify_employee(uid)
    query = f"""
        SELECT SUM(price) as my_monthly_revenue, COUNT(record_id) as monthly_transactions
        FROM employee_sales_log
        WHERE employee_id = {uid}
          AND YEAR(transaction_date)  = YEAR(CURDATE())
          AND MONTH(transaction_date) = MONTH(CURDATE())
    """
    df   = pd.read_sql(query, engine)
    data = safe_to_dict(df.round(2))
    return {"data": data, "warnings": [], "chart": None}

def get_my_total_units_sold(uid):
    """Total units sold by this employee (all time)."""
    verify_employee(uid)
    query = f"SELECT SUM(amount) as my_total_units FROM employee_sales_log WHERE employee_id = {uid}"
    df    = pd.read_sql(query, engine)
    return {"data": safe_to_dict(df), "warnings": [], "chart": None}

def get_my_average_deal_size(uid):
    """Average transaction value for this employee."""
    verify_employee(uid)
    query = f"SELECT AVG(price) as my_avg_deal_size FROM employee_sales_log WHERE employee_id = {uid}"
    df    = pd.read_sql(query, engine)
    return {"data": safe_to_dict(df.round(2)), "warnings": [], "chart": None}

def get_my_top_products(uid):
    """Top 5 products by revenue for this employee."""
    verify_employee(uid)
    query = f"""
        SELECT p.name, p.model,
               SUM(esl.amount) as units_sold,
               SUM(esl.price)  as revenue_generated
        FROM employee_sales_log esl
        JOIN product_sold_log psl ON esl.record_id  = psl.record_id
        JOIN product p            ON psl.product_id = p.product_id
        WHERE esl.employee_id = {uid}
        GROUP BY p.product_id, p.name, p.model
        ORDER BY revenue_generated DESC LIMIT 5
    """
    df    = pd.read_sql(query, engine)
    chart = generate_chart(df, 'bar', 'My Top Products by Revenue',
                           x='name', y='revenue_generated')
    return {"data": safe_to_dict(df.round(2)), "warnings": [], "chart": chart}

def get_my_sales_trend(uid):
    """Monthly revenue trend for this employee over the last 12 months."""
    verify_employee(uid)
    query = f"""
        SELECT CONCAT(YEAR(transaction_date), '-',
                      LPAD(MONTH(transaction_date), 2, '0')) as month,
               SUM(price)  as revenue,
               SUM(amount) as units
        FROM employee_sales_log
        WHERE employee_id = {uid}
          AND transaction_date >= DATE_SUB(CURDATE(), INTERVAL 12 MONTH)
        GROUP BY month ORDER BY month ASC
    """
    df    = pd.read_sql(query, engine)
    chart = generate_chart(df, 'line', 'My 12-Month Revenue Trend', x='month', y='revenue')
    return {"data": safe_to_dict(df.round(2)), "warnings": [], "chart": chart}

def get_my_recent_transactions(uid):
    """Last 10 transactions for this employee."""
    verify_employee(uid)
    query = f"""
        SELECT esl.record_id, esl.transaction_date,
               p.name as product_name, esl.amount, esl.price
        FROM employee_sales_log esl
        JOIN product_sold_log psl ON esl.record_id  = psl.record_id
        JOIN product p            ON psl.product_id = p.product_id
        WHERE esl.employee_id = {uid}
        ORDER BY esl.transaction_date DESC LIMIT 10
    """
    df = pd.read_sql(query, engine)
    return {"data": safe_to_dict(df), "warnings": [], "chart": None}

